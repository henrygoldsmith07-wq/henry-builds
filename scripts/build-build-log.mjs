import fs from "node:fs";
import path from "node:path";

/**
 * Builds the engineering build log from decisions the registry already records.
 *
 * The brief asked for an engineering journal. The temptation is to write one —
 * a Markdown file with dated entries describing how the site was built and why.
 * That would be fabrication: it would invent a history of decisions, and the
 * entry dates would be today, not when anything was actually decided.
 *
 * So the log is *derived* instead. Every entry below points at something the
 * registry genuinely holds:
 *
 *   decision   — a recorded trade-off or a limitation, i.e. a constraint that
 *                was consciously accepted;
 *   dead-end   — a recorded failedApproach, of which the archive currently has
 *                three, which is the most valuable content on the site and was
 *                previously buried at the bottom of a case study;
 *   lesson     — a recorded lesson.
 *
 * Nothing is written by this script. It only reorders existing evidence into
 * reverse-chronological reading order and labels what kind of event each is.
 */

const dir = "registry/case-studies";
const entries = [];

for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".json"))) {
  const study = JSON.parse(fs.readFileSync(path.join(dir, file), "utf8"));
  if (study.publish === false) continue;
  const cs = study.caseStudy;
  if (!cs) continue;

  for (const item of cs.failedApproaches ?? []) {
    entries.push({
      kind: "dead-end",
      date: null,
      slug: study.slug,
      project: study.name,
      title: item.approach,
      body: item.whyItFailed,
      change: item.whatItChanged ?? null,
      sortKey: 0,
    });
  }

  for (const item of cs.tradeoffs ?? []) {
    entries.push({
      kind: "decision",
      date: null,
      slug: study.slug,
      project: study.name,
      // Tradeoff is { choice, gained, gaveUp } — both sides are kept because
      // a trade-off with only one side is a rationalisation.
      title: item.choice,
      body: [item.gaveUp, item.gained && `Gained: ${item.gained}`].filter(Boolean).join(" "),
      change: null,
      sortKey: 1,
    });
  }

  for (const lesson of cs.lessons ?? []) {
    entries.push({
      kind: "lesson",
      date: null,
      slug: study.slug,
      project: study.name,
      title: null,
      body: lesson,
      change: null,
      sortKey: 2,
    });
  }

  // Limitations are plain strings in the schema, not objects.
  for (const limitation of cs.limitations ?? []) {
    entries.push({
      kind: "limitation",
      date: null,
      slug: study.slug,
      project: study.name,
      title: null,
      body: typeof limitation === "string" ? limitation : JSON.stringify(limitation),
      change: null,
      sortKey: 3,
    });
  }
}

const out = {
  _generated: true,
  _note:
    "Generated by scripts/build-build-log.mjs from recorded trade-offs, failed approaches, " +
    "lessons and limitations in the case studies. Not hand-authored: there are no invented " +
    "entries here, and no entry carries a date because the registry does not record one. " +
    "Dates will appear as `lastVerifiedAt` coverage grows; until then the log is ordered by " +
    "kind and project rather than pretending to a chronology it cannot support.",
  generatedAt: new Date().toISOString(),
  entries,
};

fs.writeFileSync(path.join("registry", "build-log.json"), `${JSON.stringify(out, null, 2)}\n`);

const counts = entries.reduce((acc, e) => ({ ...acc, [e.kind]: (acc[e.kind] ?? 0) + 1 }), {});
console.log(`build-log: ${entries.length} entries from recorded evidence`);
for (const [kind, n] of Object.entries(counts)) console.log(`  ${kind}: ${n}`);